func TestBacklinkGapServesCacheWithoutVendorCall(t *testing.T) {
	database := honestyDB(t)
	u, p := honestyUserProject(t, database)
	seoRepo := repository.NewSEORepository(database)
	payload, _ := json.Marshal(services.BacklinkGapResult{
		Target:         "example.com",
		Competitor:     "rival.com",
		Source:         "dataforseo",
		LocationCode:   services.DataForSEOLocation,
		LanguageCode:   services.DataForSEOLanguage,
		IntersectionOK: true,
		Referring: []services.ReferringDomain{
			{Domain: "news.example", Rank: 42, Backlinks: 11},
		},
		FetchedAt: time.Now().UTC(),
	})
	if err := seoRepo.SaveVendorBacklinkGapSnapshot(&models.VendorBacklinkGapSnapshot{
		Target:       "example.com",
		Competitor:   "rival.com",
		LocationCode: services.DataForSEOLocation,
		LanguageCode: services.DataForSEOLanguage,
		Source:       "dataforseo",
		Payload:      string(payload),
		FetchedAt:    time.Now().UTC(),
	}); err != nil {
		t.Fatal(err)
	}

	fake := &configuredDFS{}
	h := NewSEOHandler(
		repository.NewProjectRepository(database),
		seoRepo,
		repository.NewOAuthRepository(database),
		fake,
		nil, nil, nil,
	)
	r := gin.New()
	r.GET("/seo/backlink-gap", withUser(u.ID, h.BacklinkGap))
	req := httptest.NewRequest(http.MethodGet, "/seo/backlink-gap?project_id="+itoa(p.ID)+"&competitor=rival.com", nil)
	w := httptest.NewRecorder()
	r.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("status=%d body=%s", w.Code, w.Body.String())
	}
	var data struct {
		Available bool `json:"available"`
		Cached    bool `json:"cached"`
		Referring []struct {
			Domain string `json:"domain"`
			Rank   int    `json:"rank"`
		} `json:"referring"`
	}
	if err := json.Unmarshal(decodeData(t, w.Body.Bytes()), &data); err != nil {
		t.Fatal(err)
	}
	if !data.Available || !data.Cached || len(data.Referring) != 1 || data.Referring[0].Domain != "news.example" || data.Referring[0].Rank != 42 {
		t.Fatalf("got %+v", data)
	}
	if fake.calls != 0 {
		t.Fatalf("vendor calls=%d want 0 on fresh cache", fake.calls)
	}
}

